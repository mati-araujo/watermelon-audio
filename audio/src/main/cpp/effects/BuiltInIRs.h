/**
 * Get IR data for a cabinet type
 * @param type Cabinet type
 * @return Pointer to IR data array, or nullptr for CUSTOM
 */
inline const float* getIRData(CabinetType type) {
    switch (type) {
        case CabinetType::FENDER_1X12:
            return FENDER_1X12_IR.data();
        case CabinetType::VOX_2X12:
            return VOX_2X12_IR.data();
        case CabinetType::MARSHALL_4X12_STRAIGHT:
            return MARSHALL_4X12_STRAIGHT_IR.data();
        case CabinetType::MARSHALL_4X12_SLANT:
            return MARSHALL_4X12_SLANT_IR.data();
        case CabinetType::MESA_4X12:
            return MESA_4X12_IR.data();
        case CabinetType::BASS_1X15:
            return BASS_1X15_IR.data();
        case CabinetType::CUSTOM:
        default:
            return nullptr;
    }
}

